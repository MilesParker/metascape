/* global console */
//
// One-off conversion of the Long House Valley data files distributed with
// Ascape 5.6.1 (legacy/ascape/org.ascape.models.brook/res/edu/brook/aa/MapData)
// into the TypeScript module `long-house-valley-data.ts` beside this script.
//
// The files are embedded byte for byte, as base64, so that the decoding in
// `decode.ts` reads exactly what the Java code read with DataInputStream
// (big-endian 16-bit shorts and 32-bit IEEE floats). Run from the repository
// root of the aiscape checkout:
//
//   node metascape/packages/models/src/brookings/anasazi/data/convert.mjs
//
// It also prints a SHA-256 digest of every file, recorded in the README.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(
  here,
  '../../../../../../../legacy/ascape/org.ascape.models.brook/res/edu/brook/aa/MapData',
);

/** File name, exported constant, expected size in bytes. */
const files = [
  ['map.bin', 'MAP_BIN', 80 * 120 * 2],
  ['water.bin', 'WATER_BIN', 108 * 6 * 2],
  ['settlements.bin', 'SETTLEMENTS_BIN', 488 * 12 * 2],
  ['environment.bin', 'ENVIRONMENT_BIN', (182 * 5 * 2 + 1118 * 5 * 3) * 4],
  ['adjustedPDSI.bin', 'ADJUSTED_PDSI_BIN', 4 * 1300 * 4],
];

const LINE = 96;
let out = `// SPDX-License-Identifier: EPL-2.0
//
// GENERATED by data/convert.mjs from the Long House Valley data files
// distributed with Ascape 5.6.1 (edu/brook/aa/MapData). Do not edit by hand.
// Each constant holds the original file, byte for byte, as base64; see
// decode.ts for the record layouts and README.md for what the data are.
`;
for (const [name, constant, expected] of files) {
  const bytes = readFileSync(join(source, name));
  if (bytes.length !== expected) {
    throw new Error(`${name}: expected ${expected} bytes, found ${bytes.length}`);
  }
  const digest = createHash('sha256').update(bytes).digest('hex');
  console.log(`${name}\t${bytes.length} bytes\tsha256 ${digest}`);
  const text = bytes.toString('base64');
  const lines = [];
  for (let i = 0; i < text.length; i += LINE) lines.push(`  '${text.slice(i, i + LINE)}',`);
  out += `
/** \`${name}\` (${bytes.length} bytes, sha256 ${digest}), base64. */
export const ${constant} = [
${lines.join('\n')}
].join('');
`;
}
writeFileSync(join(here, 'long-house-valley-data.ts'), out);
